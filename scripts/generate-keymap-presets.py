#!/usr/bin/env python3
"""Generate Go keymap presets from the pinned OpenIDEA TypeScript sources."""

from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party" / "openidea" / "src" / "platform" / "keymaps"
OUTPUT = ROOT / "internal" / "app" / "keymap_presets_generated.go"

TITLES = [
    ("intellij-macos", "macOS"),
    ("intellij-windows", "Windows"),
    ("vscode-macos", "VS Code (macOS)"),
    ("vscode-windows", "VS Code (Windows)"),
    ("eclipse-macos", "Eclipse (macOS)"),
    ("eclipse-windows", "Eclipse"),
]


def parse_keymap(filename: str) -> dict[str, list[str]]:
    """Read the literal entries of one preset without evaluating TypeScript."""
    lines = (SOURCE / filename).read_text(encoding="utf-8").splitlines()
    entries: dict[str, list[str]] = {}
    inside = False
    for line_number, line in enumerate(lines, 1):
        if "export const " in line and ": Record<string, string[]> = {" in line:
            inside = True
            continue
        if inside and line.strip() == "};":
            break
        if not inside or not line.lstrip().startswith('"'):
            continue
        key_end = line.find('"', line.find('"') + 1)
        if key_end < 0:
            raise SystemExit(f"{filename}:{line_number}: malformed action id")
        action_id = json.loads(line[: key_end + 1])
        remainder = line[key_end + 1 :]
        start = remainder.find("[")
        end = remainder.rfind("]")
        if start < 0 or end < start:
            raise SystemExit(f"{filename}:{line_number}: malformed binding array")
        try:
            bindings = json.loads(remainder[start : end + 1])
        except json.JSONDecodeError as error:
            raise SystemExit(
                f"{filename}:{line_number}: malformed binding array: {error}"
            ) from error
        if not isinstance(bindings, list) or not all(
            isinstance(binding, str) for binding in bindings
        ):
            raise SystemExit(f"{filename}:{line_number}: bindings must be strings")
        entries[action_id] = bindings
    if not entries:
        raise SystemExit(f"{filename}: no preset entries found")
    return entries


def merged(
    parent: dict[str, list[str]], child: dict[str, list[str]]
) -> dict[str, list[str]]:
    """Apply TypeScript object spread order: overridden ids keep their position."""
    out = dict(parent)
    for action_id, bindings in child.items():
        out[action_id] = bindings
    return out


def windows_binding(binding: str) -> str | None:
    """Translate Meta to Ctrl unless one stroke also already uses Ctrl."""
    strokes = []
    for stroke in binding.split(" "):
        parts = stroke.split("+")
        if "Meta" in parts and "Ctrl" in parts:
            return None
        strokes.append("+".join("Ctrl" if part == "Meta" else part for part in parts))
    return " ".join(strokes)


def write_go(presets: dict[str, dict[str, list[str]]]) -> None:
    lines = [
        "// Code generated by scripts/generate-keymap-presets.py; DO NOT EDIT.",
        "",
        "package app",
        "",
        "// keymapPresetDefinitions is the pinned OpenIDEA preset set in menu order.",
        "// Entries and bindings retain the TypeScript source order because keyboard",
        "// dispatch gives later preset bindings priority.",
        "var keymapPresetDefinitions = []keymapPresetDefinition{",
    ]
    for preset_id, title in TITLES:
        lines.append(f'\t{{ID: {json.dumps(preset_id)}, Title: {json.dumps(title)}, Actions: []keymapActionDefinition{{')
        for action_id, bindings in presets[preset_id].items():
            rendered = ", ".join(json.dumps(binding) for binding in bindings)
            if rendered:
                rendered = "[]string{" + rendered + "}"
            else:
                rendered = "nil"
            lines.append(
                f"\t\t{{ID: {json.dumps(action_id)}, Bindings: {rendered}}},"
            )
        lines.append("\t}},")
    lines.extend(["}", ""])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    intellij_macos = parse_keymap("intellij-macos.ts")
    intellij_windows = parse_keymap("intellij-windows.ts")
    vscode_macos = parse_keymap("vscode-macos.ts")

    vscode_windows = {
        action_id: [
            translated
            for binding in bindings
            if (translated := windows_binding(binding)) is not None
        ]
        for action_id, bindings in vscode_macos.items()
    }
    vscode_windows = merged(
        vscode_windows, parse_keymap("vscode-windows.ts")
    )

    presets = {
        "intellij-macos": intellij_macos,
        "intellij-windows": intellij_windows,
        "vscode-macos": vscode_macos,
        "vscode-windows": vscode_windows,
        "eclipse-macos": merged(
            intellij_macos, parse_keymap("eclipse-macos.ts")
        ),
        "eclipse-windows": merged(
            intellij_windows, parse_keymap("eclipse-windows.ts")
        ),
    }
    write_go(presets)


if __name__ == "__main__":
    main()
