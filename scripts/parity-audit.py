#!/usr/bin/env python3
"""Generate PARITY_AUDIT.md: the section-5 audit of every OpenIDEA item
GoIDEA has not integrated, grouped by the goal's five areas and classified:

  A  BACKEND_REUSE   the server serves the needed command; wire RPC + UI
  B  CLIENT_PORT     upstream carries client-side orchestration under
                     src/features/<dir> that must be ported 1:1 first
  C  NATIVE_UI       a React/TSX page or component to rebuild with MyGo
  D  UPSTREAM_BLOCKED the desktop shell registers the command but
                     openidea-server --stdio does not serve it

Classification is derived from the same data OPENIDEA_PARITY_MATRIX.md uses
(scripts/openidea-parity.py), so the audit cannot drift from the pin:
 - a command served over stdio is A, one only the desktop shell has is D;
 - an item whose feature folder carries orchestration (more than 200
   non-test source lines) is B;
 - overlays and dialogs are C;
 - a status of blocked is D.

Usage:
  scripts/parity-audit.py          # rewrite PARITY_AUDIT.md
  scripts/parity-audit.py --check  # fail when the document is stale
"""

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load_parity():
    spec = importlib.util.spec_from_file_location(
        "openidea_parity", ROOT / "scripts" / "openidea-parity.py"
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# The goal's five areas and the upstream feature folders each covers.
AREAS = [
    ("项目管理", ["project-tree", "project-trust", "welcome", "remote-dev"]),
    ("Java", ["code-insight", "tools", "coverage"]),
    ("Run / Debug", ["run", "debugger", "testing", "build", "build-tools"]),
    ("构建", ["build", "build-tools"]),
    ("其他", None),  # everything else
]

ORCHESTRATION_LIMIT = 200


def cell(text):
    return str(text).replace("|", "\\|")


def trim(text, width=140):
    text = " ".join(str(text).split())
    return text if len(text) <= width else text[: width - 1] + "…"


def main():
    check = "--check" in sys.argv[1:]
    parity = load_parity()
    ipc = parity.load_ipc()
    remote = ipc.remote_commands()
    status = parity.load_status()

    # The client-side orchestration each feature folder carries, which decides
    # B against A: a folder that is only glue over RPC is A, one with real
    # frontend flow code is B.
    orch = {}
    for rel, text in parity.sources():
        d = parity.feature_of(rel)
        if not d:
            continue
        lines = 0
        for line in text.splitlines():
            s = line.strip()
            if s and not s.startswith("//") and not s.startswith("*") and not s.startswith("/*"):
                lines += 1
        orch[d] = orch.get(d, 0) + lines

    acts = parity.actions()
    tools = parity.dedupe(parity.registrations("registerToolWindow", ("id", "title", "anchor")), "id")
    overlays = parity.dedupe(parity.registrations("registerOverlay", ("id",)), "id")
    contributions = parity.dedupe(parity.registrations("registerEditorContribution", ("id",)), "id")
    pages = parity.settings_pages()
    langs = parity.languages()

    def classify(key, st, source_dir, kind):
        if st == "blocked":
            return "D"
        if st == "missing" or st == "partial":
            if kind == "command":
                return "A" if key.split(":", 1)[1] in remote else "D"
            if kind == "overlay" or kind == "editor-contribution":
                return "C"
            if source_dir and orch.get(source_dir, 0) > ORCHESTRATION_LIMIT:
                return "B"
            if source_dir:
                return "A"
        return "-"

    def item_rows(area_dirs, kind):
        out = []
        for it in kind[1]:
            d = parity.feature_of(it.get("source", ""))
            key = kind[0] + ":" + it["id"]
            st, ev = parity.status_doc(status, key, status)
            if st in ("integrated", "engine"):
                continue
            if area_dirs is not None and d not in area_dirs:
                continue
            out.append((key, st, classify(key, st, d, kind[0]), d, ev))
        return out

    kinds = [
        ("feature", None), ("action", acts), ("toolwindow", tools), ("overlay", overlays),
        ("editor-contribution", contributions), ("settings-page", pages),
    ]

    w = []
    add = w.append
    add("# OpenIDEA 功能继承审计（目标第五节）")
    add("")
    add(
        "Generated by [scripts/parity-audit.py](scripts/parity-audit.py) from the same pinned"
        " source as [OPENIDEA_PARITY_MATRIX.md](OPENIDEA_PARITY_MATRIX.md);"
        " `scripts/parity-audit.py --check` fails when it is stale."
        " Every OpenIDEA item GoIDEA has not marked `integrated` is listed here, grouped by the"
        " goal's five areas, with the classification of the work it takes:"
    )
    add("")
    add("| 分类 | 含义 |")
    add("| --- | --- |")
    add("| A | BACKEND_REUSE：Server 已提供接口，直接使用 RPC |")
    add("| B | CLIENT_PORT：上游前端存在客户端流程编排（`src/features/<dir>` 超过 200 行非测试代码），按原版 1:1 移植到 Go Adapter |")
    add("| C | NATIVE_UI：React/TSX 页面和交互组件转换为 MyGo 原生组件 |")
    add("| D | UPSTREAM_BLOCKED：命令只在桌面壳注册，`openidea-server --stdio` 不提供，需改 OpenIDEA Fork 并发布配套 Server |")
    add("")

    summary = {}
    for name, dirs in AREAS:
        rows = []
        for kname, items in kinds:
            if kname == "feature" and dirs is not None:
                for d in dirs:
                    key = "feature:" + d
                    st, ev = parity.status_doc(status, key, status)
                    if st in ("integrated", "engine"):
                        continue
                    rows.append((key, st, classify(key, st, d, "feature"), d, ev))
                continue
            if kname == "feature":
                # 其他: every feature folder no earlier area claimed.
                claimed = set()
                for _, ds in AREAS[:-1]:
                    if ds:
                        claimed |= set(ds)
                for d in sorted(orch):
                    if d in claimed:
                        continue
                    key = "feature:" + d
                    st, ev = parity.status_doc(status, key, status)
                    if st in ("integrated", "engine"):
                        continue
                    rows.append((key, st, classify(key, st, d, "feature"), d, ev))
                continue
            rows += item_rows(dirs, (kname, items))
        seen = set()
        rows = [r for r in rows if not (r[0] in seen or seen.add(r[0]))]
        summary[name] = rows
        add("## " + name)
        add("")
        counts = {}
        for _, st, cl, _, _ in rows:
            counts.setdefault((st, cl), 0)
            counts[(st, cl)] += 1
        add(
            "{} 项未集成：".format(len(rows))
            + "，".join(
                "{} {}（{}）".format(st, cl, n) for (st, cl), n in sorted(counts.items())
            )
        )
        add("")
        add("| 项 | 状态 | 分类 | 上游实现 | GoIDEA 实际入口 |")
        add("| --- | --- | --- | --- | --- |")
        for key, st, cl, d, ev in sorted(rows):
            entry = trim(ev) if ev else "—"
            add("| `{}` | {} | {} | `{}` | {} |".format(key, st, cl, d or "—", entry))
        add("")

    languages = [l for l in langs if l["id"] != "java"]
    add("## 语言与命令补充")
    add("")
    add(
        "语言 {} 个（Java 已集成）；OpenIDEA 桌面壳注册 {} 条 IPC 命令，stdio 提供 {} 条：".format(
            len(languages), len(ipc.tauri_commands()), len(remote)
        )
    )
    add("")
    add("| 命令 | stdio | 状态 | 分类 |")
    add("| --- | --- | --- | --- |")
    for _module, name in ipc.tauri_commands():
        st, ev = parity.status_doc(status, "command:" + name, status)
        if st in ("integrated", "engine"):
            continue
        cl = "A" if name in remote else "D"
        add("| `{}` | {} | {} | {} |".format(name, "yes" if name in remote else "no", st, cl))
    add("")

    text = "\n".join(w) + "\n"
    doc = ROOT / "PARITY_AUDIT.md"
    if check:
        current = doc.read_text(encoding="utf-8") if doc.exists() else None
        if current != text:
            sys.exit("PARITY_AUDIT.md is stale: run scripts/parity-audit.py")
        print("PARITY_AUDIT.md is current")
        return
    doc.write_text(text, encoding="utf-8")
    counts = {name: len(rows) for name, rows in summary.items()}
    print("wrote PARITY_AUDIT.md:", counts)


if __name__ == "__main__":
    main()
